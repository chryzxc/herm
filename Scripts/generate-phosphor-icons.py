#!/usr/bin/env python3
"""Vendor Phosphor icon paths into Sources/Herm/Workspace/PhosphorIcons.swift.

Phosphor is the app's only icon family. The official Swift package ships an
asset catalog, which `swift build` cannot compile, so the SVG path data is
generated into Swift instead and drawn by `DockIcon`.

Usage:
    Scripts/generate-phosphor-icons.py [path-to-phosphor-icons/core checkout]

Without a path, the pinned commit below is shallow-cloned into a temp dir.
Every icon is vendored in the regular weight; only FILLED icons also get the
fill weight. Add a name there when a solid variant is needed.
"""
import pathlib
import re
import subprocess
import sys
import tempfile

CORE_REPO = "https://github.com/phosphor-icons/core.git"
CORE_COMMIT = "2b75f3ad12b420c9504ef05df8d2564a28f8500e"  # @phosphor-icons/core 2.1.1
FILLED = {"play", "pause", "stop", "fast-forward", "pause-circle", "x-circle", "check-circle", "circle", "push-pin"}
SWIFT_KEYWORDS = {"repeat", "import", "return", "switch", "case", "default", "class", "struct", "enum", "func", "var", "let",
                  "if", "else", "for", "while", "do", "in", "is", "as", "try", "throw", "true", "false", "nil", "self",
                  "super", "init", "operator", "protocol", "extension", "static", "where", "break", "continue", "defer",
                  "guard", "inout", "internal", "private", "public", "subscript", "typealias", "Type", "Any"}
OUTPUT = pathlib.Path(__file__).resolve().parent.parent / "Sources/Herm/Workspace/PhosphorIcons.swift"


def case_name(slug: str) -> str:
    head, *rest = slug.split("-")
    name = head + "".join(part[:1].upper() + part[1:] for part in rest)
    return f"`{name}`" if name in SWIFT_KEYWORDS else name


def path_data(svg: pathlib.Path) -> str:
    return " ".join(re.findall(r' d="([^"]+)"', svg.read_text()))


def generate(core: pathlib.Path) -> str:
    regular = sorted((core / "assets/regular").glob("*.svg"))
    slugs = [svg.stem for svg in regular]
    missing = FILLED - set(slugs)
    if missing:
        sys.exit(f"FILLED names not in Phosphor: {sorted(missing)}")
    lines = [
        "// GENERATED by Scripts/generate-phosphor-icons.py. Do not edit.",
        "// Phosphor Icons 2.1.1, https://phosphoricons.com",
        "// MIT License, Copyright (c) 2023 Phosphor Icons.",
        "// Paths are filled outlines on a 256x256 grid.",
        "",
        "// swift-format-ignore-file",
        "enum Ph: CaseIterable {",
        *(f"    case {case_name(slug)}" for slug in slugs),
        "}",
        "",
        "extension Ph {",
        "    var regularPath: String {",
        "        switch self {",
        *(f'        case .{case_name(svg.stem).strip("`")}: return "{path_data(svg)}"' for svg in regular),
        "        }",
        "    }",
        "",
        "    var fillPath: String? {",
        "        switch self {",
        *(f'        case .{case_name(slug).strip("`")}: return "{path_data(core / "assets/fill" / f"{slug}-fill.svg")}"'
          for slug in sorted(FILLED)),
        "        default: return nil",
        "        }",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    if len(sys.argv) > 1:
        OUTPUT.write_text(generate(pathlib.Path(sys.argv[1])))
        return
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(["git", "init", "-q", tmp], check=True)
        subprocess.run(["git", "-C", tmp, "fetch", "-q", "--depth", "1", CORE_REPO, CORE_COMMIT], check=True)
        subprocess.run(["git", "-C", tmp, "checkout", "-q", "FETCH_HEAD"], check=True)
        OUTPUT.write_text(generate(pathlib.Path(tmp)))


if __name__ == "__main__":
    main()
