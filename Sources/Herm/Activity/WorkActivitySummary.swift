import Foundation
import SwiftUI

/// Bounded metadata only: no transcripts, tool payloads, paths, or automation output.
struct WorkActivitySummaryInput: Equatable {
    let scope: String
    let prompt: String?

    init(range: WorkRange, scope: String) {
        self.scope = scope
        guard !range.isEmpty else {
            prompt = nil
            return
        }
        func date(_ value: Date) -> String { value.formatted(.iso8601.year().month().day()) }
        func title(_ value: String) -> String {
            String(HermesDiagnosticsService.safeSummary(value).prefix(140))
                .split(whereSeparator: \.isWhitespace).joined(separator: " ")
        }
        var lines = [
            "Scope: \(scope). Only recorded activity in the loaded month is included.",
            "Recorded dates: \(range.points.first.map { date($0.date) } ?? "unknown") through \(range.points.last.map { date($0.date) } ?? "unknown").",
            "Totals: \(range.pullRequests.count) merged PRs, \(range.tasks.count) completed tasks, \(range.commits.count) commits, \(range.sessions.count) sessions, \(range.runs.count) automation runs (\(range.runs.filter(\.isFailure).count) failed).",
        ]
        if range.hasUsage {
            lines.append("Recorded usage: \(range.tokens) tokens, \(range.apiCalls) API calls.")
        }
        // Each category gets its own budget, so a busy repository cannot crowd out other work.
        lines.append("Detail samples (up to 8 per category; not a complete list):")
        lines += range.pullRequests.prefix(8).map { "Merged PR: \(title($0.title))" }
        lines += range.tasks.prefix(8).map { "Completed task: \(title($0.title))" }
        lines += range.commits.prefix(8).map { "Commit: \(title($0.subject))" }
        lines += range.sessions.prefix(8).map { "Session (completion unknown): \(title($0.title))" }
        prompt = lines.joined(separator: "\n")
    }
}

struct WorkActivitySummaryView: View {
    let input: WorkActivitySummaryInput?
    @Environment(\.dockWorkspaceScale) private var workspaceScale
    @State private var completedInput: WorkActivitySummaryInput?
    @State private var summary: String?
    @State private var isGenerating = false
    @State private var retry = 0

    private struct Request: Equatable {
        let input: WorkActivitySummaryInput?
        let retry: Int
    }

    var body: some View {
        VStack(alignment: .leading, spacing: 10) {
            HStack(spacing: 8) {
                Text("\(input?.scope ?? "Activity") summary").dockFont(.body, weight: .semibold)
                Spacer(minLength: 0)
                if isGenerating { ProgressView().controlSize(.small) }
            }
            ScrollView {
                VStack(alignment: .leading, spacing: 8) {
                    if input == nil {
                        Text("Summary unavailable until activity is loaded. Refresh Activity to try again.")
                    } else if input?.prompt == nil {
                        Text("No recorded activity for this period.")
                    } else if !OnDeviceAssist.isAvailable {
                        Text(OnDeviceAssist.unavailableMessage)
                    } else if completedInput == input, let summary {
                        MarkdownMessageView(
                            markdown: summary, bodySize: DockTypography.size(.body, scale: workspaceScale)
                        )
                    } else if completedInput == input {
                        Text("Couldn’t generate a summary. Try again.")
                        Button("Try again") { retry += 1 }.buttonStyle(.dockCompact)
                    } else {
                        Text("Summarizing recorded activity…")
                    }
                }
                .frame(maxWidth: .infinity, alignment: .topLeading)
            }
            .frame(height: 180)
            .dockFont(.body)
            .foregroundStyle(Color.dockSecondaryText)
            OnDeviceAssistNotice(
                text: summary != nil && completedInput == input
                    ? "Generated by Apple Intelligence" : "Uses Apple Intelligence on this Mac",
                help: OnDeviceAssist.generatedTextHelp
                    + " Summaries use recorded counts and title samples and may omit details. Weeks include only the loaded month."
            )
        }
        .frame(maxWidth: .infinity, minHeight: 130, alignment: .topLeading)
        .dockCard(padding: 14)
        .task(id: Request(input: input, retry: retry)) { await generate() }
    }

    @MainActor private func generate() async {
        summary = nil
        completedInput = nil
        isGenerating = false
        guard let input, let prompt = input.prompt, OnDeviceAssist.isAvailable else { return }
        isGenerating = true
        // Calendar keyboard navigation should not start a model request for every intermediate day.
        try? await Task.sleep(for: .milliseconds(350))
        guard !Task.isCancelled else { return }
        let result = await OnDeviceAssist.summarizeActivity(prompt)
        guard !Task.isCancelled else { return }
        summary = result
        completedInput = input
        isGenerating = false
    }
}
