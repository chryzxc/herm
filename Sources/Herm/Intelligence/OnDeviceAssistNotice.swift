import SwiftUI

/// Shared attribution for on-device assistance; only the icon carries an accent.
struct OnDeviceAssistNotice: View {
    var text = "Generated by Apple Intelligence"
    var help = OnDeviceAssist.generatedTextHelp

    var body: some View {
        HStack(alignment: .firstTextBaseline, spacing: 4) {
            DockIcon(.info, size: 12, color: DockAccentColor.orange.color)
                .accessibilityHidden(true)
            Text(text)
                .dockFont(.body)
                .foregroundStyle(Color.dockMetadataText)
                .fixedSize(horizontal: false, vertical: true)
        }
        .dockPadding(.horizontal, 6)
        .dockPadding(.vertical, 3)
        .dockWell()
        .help(help)
        .accessibilityElement(children: .combine)
        .accessibilityHint(help)
    }
}
