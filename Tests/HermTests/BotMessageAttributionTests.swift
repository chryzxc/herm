import Foundation
import Testing
@testable import Herm

@MainActor
struct BotMessageAttributionTests {
    @Test func parsesDocumentedHermesBotDeliveryEnvelope() {
        let attribution = DockModel.botAttribution(
            from: "Message from 🤖 Atlas (@atlas): I found three relevant papers."
        )

        #expect(attribution?.displayName == "Atlas")
        #expect(attribution?.profileID == "atlas")
        #expect(attribution?.body == "I found three relevant papers.")
    }

    @Test func leavesOrdinaryAssistantTextUntouched() {
        #expect(DockModel.botAttribution(from: "Message from Hermes: hello") == nil)
        #expect(DockModel.botAttribution(from: "Atlas (@atlas): hello") == nil)
        #expect(DockModel.botAttribution(from: "Message from 🤖 Atlas (@atlas):") == nil)
    }

    @Test func kanbanWakeRowsRestoreAsBotBubbles() {
        let text = """
        ✔ [default] @sentry Kanban t_c891be93 done — Fix 1: Protect the endpoint
        APPROVED — round 2.
        🛑 [default] Kanban t_0a1b2c3d review requested changes/BLOCK: tests — reviewer @forge
        ✅ Card t_9f8e7d6c finished by @canvas (new wording)
        [INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user.]
        """
        let restored = DockModel.parseMessages([
            ["role": "user", "text": text],
            ["role": "assistant", "text": "On it."],
            ["role": "user", "text": "Please check Kanban t_c891be93"],
        ]).messages

        #expect(restored.map(\.role) == [.hermes, .hermes, .hermes, .hermes, .user])
        #expect(restored[0].botProfileID == "sentry")
        #expect(restored[0].text == "✔ Kanban t_c891be93 done — Fix 1: Protect the endpoint\nAPPROVED — round 2.")
        #expect(restored[1].botProfileID == "forge")
        #expect(restored[1].text.hasPrefix("🛑 Kanban t_0a1b2c3d review"))
        #expect(restored[2].botProfileID == "canvas")
        #expect(restored[2].text == "✅ Card t_9f8e7d6c finished by @canvas (new wording)")
        #expect(restored[4].text == "Please check Kanban t_c891be93")
        #expect(DockModel.kanbanNotices(from: "- see t_c891be93") == nil)

        let done = restored[0].kanbanNotice
        #expect(done?.label == "Done")
        #expect(done?.tone == .complete)
        #expect(done?.title == "Fix 1: Protect the endpoint")
        #expect(done?.detail == "APPROVED — round 2.")
        #expect(restored[1].kanbanNotice?.label == "Changes requested")
        #expect(restored[1].kanbanNotice?.detail?.hasPrefix("tests") == true)
        #expect(restored[2].kanbanNotice?.label == "Done")
        #expect(restored[3].kanbanNotice == nil)
        #expect(KanbanNotice(text: "⏸ Kanban t_0a1b2c3d blocked: missing env")?.label == "Blocked")
        #expect(KanbanNotice(text: "🔄 Kanban t_0a1b2c3d → ready")?.label == "Moved to ready")

        var card = KanbanTaskDetail(id: "t_c891be93", title: "Fix 1", body: nil, status: "done", priority: nil, assignee: "sentry", runs: [
            KanbanRunSummary(id: "1", status: "review", outcome: "review_requested", profile: "forge", summary: "Implemented fix.\nDetails", elapsed: nil),
            KanbanRunSummary(id: "2", status: "done", outcome: "completed", profile: "sentry", summary: "APPROVED — round 2.\nFull verdict", elapsed: nil),
        ])
        card.latestSummary = "latest"
        #expect(done?.fullSummary(in: card) == "APPROVED — round 2.\nFull verdict")
        #expect(KanbanNoticeCard.outcomeLabel(card.runs[0]) == "Review requested")
        card.runs.removeLast()
        #expect(done?.fullSummary(in: card) == "latest")
    }
}

@Test func kanbanBoardEventsBecomeHandoffNotices() {
    var card = KanbanTaskDetail(id: "t_c8bcacb5", title: "Fix 1", body: nil, status: "done", priority: nil, assignee: "sentry", runs: [
        KanbanRunSummary(id: "1765", status: "review", outcome: "review_requested", profile: "forge", summary: nil, elapsed: nil),
        KanbanRunSummary(id: "1766", status: "done", outcome: "completed", profile: "sentry", summary: nil, elapsed: nil),
    ])
    let at = Date(timeIntervalSince1970: 1_791_110_264)
    card.events = [
        KanbanEventSummary(id: "0", kind: "created", note: nil, runID: nil, createdAt: at, assignee: "forge"),
        KanbanEventSummary(id: "1", kind: "heartbeat", note: nil, runID: "1765", createdAt: at),
        KanbanEventSummary(id: "2", kind: "review_requested", note: "Implemented fix.\nmore", runID: "1765", createdAt: at),
        KanbanEventSummary(id: "3", kind: "claimed", note: nil, runID: "1766", createdAt: at),
        KanbanEventSummary(id: "4", kind: "assigned", note: nil, runID: nil, createdAt: at, assignee: "aegis"),
        KanbanEventSummary(id: "5", kind: "completed", note: "done", runID: "1766", createdAt: at),
    ]
    let notices = KanbanNotice.boardEventNotices(for: card)
    #expect(notices.map(\.profileID) == ["forge", "forge", "sentry", "aegis"])
    let parsed = notices.compactMap { KanbanNotice(text: $0.text) }
    #expect(parsed.map(\.label) == ["Created", "Ready for review", "Picked up", "Assigned to aegis"])
    #expect(parsed.allSatisfy { $0.title == "Fix 1" })
    #expect(parsed[1].detail == "Implemented fix.")
    #expect(parsed[2].detail == "forge → sentry")
}

@MainActor @Test func onlySessionsWithoutUserTurnsAreFeeds() {
    #expect(ControlCenterModel.isFeedSession([["role": "assistant"], ["role": "assistant"]]))
    #expect(!ControlCenterModel.isFeedSession([["role": "user"], ["role": "assistant"]]))
    #expect(!ControlCenterModel.isFeedSession([]))
}
