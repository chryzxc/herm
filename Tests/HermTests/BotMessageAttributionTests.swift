import Testing
@testable import Herm

@MainActor
struct BotMessageAttributionTests {
    @Test func parsesDocumentedHermesBotDeliveryEnvelope() {
        let attribution = DockModel.botAttribution(
            from: "Message from 🤖 Atlas (@atlas): I found three relevant papers."
        )

        #expect(attribution?.displayName == "Atlas")
        #expect(attribution?.profileID == "atlas")
        #expect(attribution?.body == "I found three relevant papers.")
    }

    @Test func leavesOrdinaryAssistantTextUntouched() {
        #expect(DockModel.botAttribution(from: "Message from Hermes: hello") == nil)
        #expect(DockModel.botAttribution(from: "Atlas (@atlas): hello") == nil)
        #expect(DockModel.botAttribution(from: "Message from 🤖 Atlas (@atlas):") == nil)
    }

    @Test func kanbanWakeRowsRestoreAsBotBubbles() {
        let text = """
        ✔ [default] @sentry Kanban t_c891be93 done — Fix 1: Protect the endpoint
        APPROVED — round 2.
        🛑 [default] Kanban t_0a1b2c3d review requested changes/BLOCK: tests — reviewer @forge
        ✅ Card t_9f8e7d6c finished by @canvas (new wording)
        [INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user.]
        """
        let restored = DockModel.parseMessages([
            ["role": "user", "text": text],
            ["role": "assistant", "text": "On it."],
            ["role": "user", "text": "Please check Kanban t_c891be93"],
        ]).messages

        #expect(restored.map(\.role) == [.hermes, .hermes, .hermes, .hermes, .user])
        #expect(restored[0].botProfileID == "sentry")
        #expect(restored[0].text == "✔ Kanban t_c891be93 done — Fix 1: Protect the endpoint\nAPPROVED — round 2.")
        #expect(restored[1].botProfileID == "forge")
        #expect(restored[1].text.hasPrefix("🛑 Kanban t_0a1b2c3d review"))
        #expect(restored[2].botProfileID == "canvas")
        #expect(restored[2].text == "✅ Card t_9f8e7d6c finished by @canvas (new wording)")
        #expect(restored[4].text == "Please check Kanban t_c891be93")
        #expect(DockModel.kanbanNotices(from: "- see t_c891be93") == nil)

        let done = restored[0].kanbanNotice
        #expect(done?.label == "Done")
        #expect(done?.tone == .complete)
        #expect(done?.title == "Fix 1: Protect the endpoint")
        #expect(done?.detail == "APPROVED — round 2.")
        #expect(restored[1].kanbanNotice?.label == "Changes requested")
        #expect(restored[1].kanbanNotice?.detail?.hasPrefix("tests") == true)
        #expect(restored[2].kanbanNotice?.label == "Done")
        #expect(restored[3].kanbanNotice == nil)
        #expect(KanbanNotice(text: "⏸ Kanban t_0a1b2c3d blocked: missing env")?.label == "Blocked")
        #expect(KanbanNotice(text: "🔄 Kanban t_0a1b2c3d → ready")?.label == "Moved to ready")
    }
}
